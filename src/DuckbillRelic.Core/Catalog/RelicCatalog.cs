using System.Text.Json;

namespace DuckbillRelic.Core.Catalog;

public enum SeriesKind { Weapon, Tool }

/// <summary>One upgrade item level: the relic item for each job (and the Paladin shield, which is not judged).</summary>
public sealed record RelicTier(IReadOnlyDictionary<uint, uint> ItemByJob, uint Shield);

/// <summary>A per-job achievement that proves a display stage for one job.</summary>
public sealed record StageAchievement(uint AchievementId, int Stage, uint Job);

/// <summary>
/// A relic series. Display stages group one or more tiers; stage s is complete when the job holds
/// the item of tier <see cref="StageTierEnds"/>[s-1] or any later tier. Stages and tiers are 1-based.
/// </summary>
public sealed class RelicSeries
{
    public required string Id { get; init; }
    public required SeriesKind Kind { get; init; }
    public required uint NameAchievementCategory { get; init; }
    public required IReadOnlyList<uint> Jobs { get; init; }
    public required IReadOnlyList<int> StageTierEnds { get; init; }
    public required IReadOnlyList<RelicTier> Tiers { get; init; }
    public required IReadOnlyList<StageAchievement> Achievements { get; init; }

    public int StageCount => StageTierEnds.Count;
    public bool HasJob(uint job) => Jobs.Contains(job);

    /// <summary>Highest display stage completed by holding an item of the given tier (0 if none).</summary>
    public int StageForTier(int tier)
    {
        var stage = 0;
        for (var s = 0; s < StageTierEnds.Count && StageTierEnds[s] <= tier; s++) stage = s + 1;
        return stage;
    }

    /// <summary>Stages that have a per-job achievement.</summary>
    public int HighestAchievementStage => Achievements.Count == 0 ? 0 : Achievements.Max(a => a.Stage);
    public bool StageHasAchievement(int stage) => Achievements.Any(a => a.Stage == stage);

    /// <summary>The item that completes a display stage for a job, used for the displayed relic name.</summary>
    public uint StageItem(int stage, uint job) =>
        stage < 1 || stage > StageCount ? 0 : Tiers[StageTierEnds[stage - 1] - 1].ItemByJob.GetValueOrDefault(job);
}

/// <summary>Where an owned item belongs. Shields are listed but never used for judgement.</summary>
public readonly record struct RelicItemRef(string SeriesId, int Tier, uint Job, bool IsShield);

public sealed class RelicCatalog
{
    private readonly Dictionary<uint, RelicItemRef> itemIndex = [];
    private readonly Dictionary<uint, (string SeriesId, StageAchievement Achievement)> achievementIndex = [];

    public RelicCatalog(IReadOnlyList<RelicSeries> series)
    {
        Series = series;
        foreach (var s in series)
        {
            for (var t = 0; t < s.Tiers.Count; t++)
            {
                foreach (var (job, item) in s.Tiers[t].ItemByJob) itemIndex[item] = new RelicItemRef(s.Id, t + 1, job, false);
                if (s.Tiers[t].Shield != 0) itemIndex[s.Tiers[t].Shield] = new RelicItemRef(s.Id, t + 1, 0, true);
            }
            foreach (var a in s.Achievements) achievementIndex[a.AchievementId] = (s.Id, a);
        }
    }

    public IReadOnlyList<RelicSeries> Series { get; }
    public RelicSeries? Get(string id) => Series.FirstOrDefault(s => s.Id == id);
    public bool TryGetItem(uint itemId, out RelicItemRef item) => itemIndex.TryGetValue(itemId, out item);
    public IEnumerable<uint> AllItemIds => itemIndex.Keys;
    public IEnumerable<uint> AllAchievementIds => achievementIndex.Keys;
    public bool TryGetAchievement(uint id, out string seriesId, out StageAchievement achievement)
    {
        if (achievementIndex.TryGetValue(id, out var hit)) { seriesId = hit.SeriesId; achievement = hit.Achievement; return true; }
        seriesId = ""; achievement = null!; return false;
    }

    /// <summary>A copy without the given series, used when a series fails its runtime contract check.</summary>
    public RelicCatalog Without(IReadOnlySet<string> disabled) => new(Series.Where(s => !disabled.Contains(s.Id)).ToList());

    /// <summary>Parse data/relic-catalog.v1.json (generated by tools/relic-catalog).</summary>
    public static RelicCatalog Parse(string json)
    {
        using var doc = JsonDocument.Parse(json);
        var root = doc.RootElement;
        if (root.GetProperty("schema").GetInt32() != 1) throw new InvalidDataException("Unsupported relic catalog schema.");
        var list = new List<RelicSeries>();
        foreach (var s in root.GetProperty("series").EnumerateArray())
        {
            var tiers = s.GetProperty("tiers").EnumerateArray().Select(t => new RelicTier(
                t.GetProperty("items").EnumerateObject().ToDictionary(p => uint.Parse(p.Name), p => p.Value.GetUInt32()),
                t.TryGetProperty("shield", out var sh) ? sh.GetUInt32() : 0)).ToList();
            list.Add(new RelicSeries
            {
                Id = s.GetProperty("id").GetString()!,
                Kind = s.GetProperty("kind").GetString() == "tool" ? SeriesKind.Tool : SeriesKind.Weapon,
                NameAchievementCategory = s.GetProperty("nameAchievementCategory").GetUInt32(),
                Jobs = s.GetProperty("jobs").EnumerateArray().Select(j => j.GetUInt32()).ToList(),
                StageTierEnds = s.GetProperty("stageTierEnds").EnumerateArray().Select(e => e.GetInt32()).ToList(),
                Tiers = tiers,
                Achievements = s.GetProperty("achievements").EnumerateArray().Select(a => new StageAchievement(
                    a.GetProperty("id").GetUInt32(), a.GetProperty("stage").GetInt32(), a.GetProperty("job").GetUInt32())).ToList(),
            });
        }
        return new RelicCatalog(list);
    }
}
